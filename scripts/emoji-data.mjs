import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

export const EMOJI_DATA_FILE = 'src/emoji/data.ts';

// emojibase numbers its groups. Group 2 holds the components, skin tones and hair styles, which are parts of emoji
// rather than emoji, and the regional indicator letters belong to no group.
const GROUPS = new Map([
  [0, 'smileys'],
  [1, 'people'],
  [3, 'animals'],
  [4, 'food'],
  [5, 'travel'],
  [6, 'activities'],
  [7, 'objects'],
  [8, 'symbols'],
  [9, 'flags'],
]);

/** The dataset of the installed emojibase-data: its version, its compact English emoji and their GitHub shortcodes. */
export function emojibase(root) {
  const read = (path) => JSON.parse(readFileSync(resolve(root, 'node_modules', 'emojibase-data', path), 'utf8'));
  return {
    version: read('package.json').version,
    compact: read('en/compact.json'),
    shortcodes: read('en/shortcodes/github.json'),
  };
}

/** Each emoji of a group in its base form, without its skin tone variants, as `[emoji, shortcodes, tags, group]`. */
export const emojiRows = (compact, shortcodes) =>
  compact.flatMap(({ unicode, hexcode, tags = [], group }) =>
    GROUPS.has(group) ? [[unicode, [shortcodes[hexcode] ?? []].flat(), tags, GROUPS.get(group)]] : [],
  );

/** The source of the data module that the installed emojibase-data makes. */
export function generateEmojiData(root) {
  const { version, compact, shortcodes } = emojibase(root);
  return [
    `// Generated by scripts/build-emoji-data.mjs from emojibase-data ${version}. Do not edit.`,
    "import type { EmojiRow } from './emoji-types';",
    '',
    'export const EMOJI_ROWS: readonly EmojiRow[] = [',
    ...emojiRows(compact, shortcodes).map((row) => `  ${JSON.stringify(row)},`),
    '];',
    '',
  ].join('\n');
}
